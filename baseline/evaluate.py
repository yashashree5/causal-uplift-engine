"""Score saved predictions the way the authors do and compare with the paper.

For each task and method: concatenate all 5 test folds, compute the normalized Qini score
(eval.qini, identical to the authors' get_qini_curve), then divide each method's score by the best
method's score for that task (paper Tables 2 and 7).

Usage:
    python -m baseline.evaluate --dataset hillstrom
    python -m baseline.evaluate --dataset criteo

Writes reports/baseline_<dataset>.md and reports/baseline_<dataset>.csv.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import numpy as np
import pandas as pd

from baseline.tasks import DATASET_TASKS, SEED, TASKS, TOLERANCE, paper_scores
from eval.qini import get_qini_curve, normalize_scores


def load(out_dir: Path, task: str) -> dict[str, pd.DataFrame]:
    preds = {}
    root = out_dir / "predictions"
    if not root.exists():
        return preds
    for method_dir in sorted(p for p in root.iterdir() if p.is_dir()):
        files = sorted((method_dir / task).glob(f"seed{SEED}_fold*.parquet"))
        if len(files) == 5:
            preds[method_dir.name] = pd.concat([pd.read_parquet(f) for f in files], ignore_index=True)
        elif files:
            print(f"warning: {method_dir.name}/{task} has {len(files)}/5 folds; skipped")
    return preds


def score_task(out_dir: Path, task: str) -> pd.DataFrame:
    preds = load(out_dir, task)
    if not preds:
        return pd.DataFrame()
    raw = {}
    for method, df in preds.items():
        _, raw[method] = get_qini_curve(
            df["t"].to_numpy(np.float64), df["y"].to_numpy(np.float64), df["uplift_pred"].to_numpy(np.float64)
        )
    norm = normalize_scores(raw)
    paper = paper_scores(task)
    rows = []
    for method in raw:
        p = paper.get(method)
        diff = norm[method] - p if p is not None else None
        rows.append(
            {
                "task": task,
                "paper_column": TASKS[task][2],
                "method": method,
                "qini_raw": raw[method],
                "qini_normalized": norm[method],
                "paper_normalized": p,
                "difference": diff,
                "within_tolerance": None if diff is None else abs(diff) <= TOLERANCE,
                "n_test_rows": len(preds[method]),
            }
        )
    return pd.DataFrame(rows).sort_values("qini_normalized", ascending=False)


def _fmt(v, digits=3):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "–"
    if isinstance(v, (bool, np.bool_)):
        return "yes" if v else "**no**"
    if isinstance(v, (float, np.floating)):
        return f"{v:.{digits}f}"
    return str(v)


def to_markdown(dataset: str, table: pd.DataFrame) -> str:
    lines = [
        f"# Baseline reproduction: {dataset.capitalize()}",
        "",
        "Generated by `python -m baseline.evaluate`. Normalized Qini: each method's Qini divided by the "
        f"best method's score for that task. Pass rule: within ±{TOLERANCE} of the paper.",
        "",
    ]
    for task, group in table.groupby("task", sort=False):
        lines += [
            f"## {task} (paper: {group['paper_column'].iloc[0]})",
            "",
            "| Method | Raw Qini | Normalized | Paper | Difference | Within tolerance |",
            "|---|---|---|---|---|---|",
        ]
        for _, r in group.iterrows():
            diff = "–" if pd.isna(r["difference"]) else f"{r['difference']:+.3f}"
            lines.append(
                f"| {r['method']} | {_fmt(r['qini_raw'], 4)} | {_fmt(r['qini_normalized'])} | "
                f"{_fmt(r['paper_normalized'])} | {diff} | {_fmt(r['within_tolerance'])} |"
            )
        lines += ["", f"Test rows per method: {int(group['n_test_rows'].iloc[0]):,}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", choices=sorted(DATASET_TASKS), required=True)
    parser.add_argument("--output-dir", default=os.environ.get("OUTPUT_DIR", "./outputs"))
    parser.add_argument("--reports-dir", default="reports")
    args = parser.parse_args()

    out_dir = Path(args.output_dir)
    tables = [score_task(out_dir, t) for t in DATASET_TASKS[args.dataset]]
    tables = [t for t in tables if not t.empty]
    if not tables:
        raise SystemExit(f"no complete predictions found under {out_dir / 'predictions'}")
    table = pd.concat(tables, ignore_index=True)

    reports = Path(args.reports_dir)
    reports.mkdir(parents=True, exist_ok=True)
    table.to_csv(reports / f"baseline_{args.dataset}.csv", index=False)
    md = to_markdown(args.dataset, table)
    (reports / f"baseline_{args.dataset}.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
